export function pickLocale(dict, locale, isRTL) {
  if (!dict) return {};
  return dict[locale] || (isRTL ? dict.ar : dict.en) || dict.en || dict.ar;
}

export function handleRovingKeyDown({ event, keys, currentKey, onSelect, isRTL = false }) {
  const index = keys.indexOf(currentKey);
  if (index === -1 || keys.length === 0) return;

  const nextKey = isRTL ? 'ArrowLeft' : 'ArrowRight';
  const prevKey = isRTL ? 'ArrowRight' : 'ArrowLeft';

  let nextIndex = null;
  if (event.key === nextKey || event.key === 'ArrowDown') {
    nextIndex = (index + 1) % keys.length;
  } else if (event.key === prevKey || event.key === 'ArrowUp') {
    nextIndex = (index - 1 + keys.length) % keys.length;
  } else if (event.key === 'Home') {
    nextIndex = 0;
  } else if (event.key === 'End') {
    nextIndex = keys.length - 1;
  }

  if (nextIndex === null) return;
  event.preventDefault();
  const targetKey = keys[nextIndex];
  onSelect(targetKey);

  const container = event.currentTarget.closest('[role="tablist"], [role="radiogroup"], [role="group"]');
  if (container) {
    const buttons = Array.from(container.querySelectorAll('button'));
    buttons[nextIndex]?.focus();
  }
}

